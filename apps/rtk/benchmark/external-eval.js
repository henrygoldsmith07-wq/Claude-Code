/** Loads a .jsonl (one task per line) or .json manifest from disk. */
function loadTasks(file) {
  const text = fs.readFileSync(file, 'utf8');
  let input;
  if (file.endsWith('.jsonl')) {
    input = text.split('\n').map((l) => l.trim()).filter(Boolean).map((l) => JSON.parse(l));
  } else {
    input = JSON.parse(text);
  }
  const validated = lib.validateTasksManifest(input);
  if (!validated.ok) throw new Error(`invalid task manifest:\n${validated.errors.map((e) => `  - ${e}`).join('\n')}`);
  return validated.tasks;
}

function makeFrozenVersions() {
  return {
    rtk: getRtkCommit(path.join(__dirname, '..')),
    corpus: getCorpusVersion(),
    harness: getBenchmarkVersion(),
  };
}

function sampleTask(i) {
  const n = String(i).padStart(2, '0');
  return {
    id: `ext-sample-${n}`,
    source: 'internal-sample',
    origin: 'SYNTHETIC PLACEHOLDER generated by --gen-sample — NOT independent evidence',
    url: null,
    prompt: `SYNTHETIC PLACEHOLDER ${n}: fix the intentionally broken fixture so "npm test" passes. This task proves harness plumbing only.`,
    taskDir: null,
    tests: { pass: 'echo ok', fail: 'echo failing-fixtures-not-run' },
    frozenVersions: makeFrozenVersions(),
    notes: 'Placeholder. Replace with independently-sourced tasks (source:"independent") before claiming external validity.',
  };
}

function genSample(outFile) {
  const lines = Array.from({ length: 12 }, (_, i) => JSON.stringify(sampleTask(i + 1)));
  fs.writeFileSync(outFile, `${lines.join('\n')}\n`);
  return outFile;
}

// ---------------------------------------------------------------------------
// Plan matrix — pure; availability injected so plan works with zero CLIs
// ---------------------------------------------------------------------------

function buildPlan({ tasks, arms, models, frameworks, availability = {} }) {
  const rows = [];
  for (const task of tasks) {
    for (const arm of arms) {
      for (const model of models) {
        for (const framework of frameworks) {
          rows.push({
            taskId: task.id,
            source: task.source,
            arm,
            model: model.id,
            tier: model.tier,
            framework,
            available: availability[framework] === true && model.provider !== 'mock',
          });
        }
      }
    }
  }
  return { rows, counts: { tasks: tasks.length, arms: arms.length, models: models.length, frameworks: frameworks.length, total: rows.length } };
}

function renderPlan(plan) {
  const lines = [];
  lines.push(`planned matrix: ${plan.counts.total} runs (${plan.counts.tasks} tasks x ${plan.counts.arms} arms x ${plan.counts.models} models x ${plan.counts.frameworks} frameworks)`);
  lines.push('');
  lines.push('taskId\tarm\tmodel\ttier\tframework\tavailable');
  for (const r of plan.rows) lines.push(`${r.taskId}\t${r.arm}\t${r.model}\t${r.tier}\t${r.framework}\t${r.available ? 'yes' : 'NO'}`);
  lines.push('');
  lines.push('dry-run: nothing was executed. Install a framework CLI or pass --framework-cmd to enable live runs.');
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// Run records
// ---------------------------------------------------------------------------

function sanitizeName(s) { return String(s).replace(/[^a-zA-Z0-9._-]+/g, '_').slice(0, 80); }

function buildRunRecord({ task, arm, model, framework, attempt, metrics, transcriptPath, seed }) {
  return {
    taskId: task.id,
    arm,
    model: model.id,
    tier: model.tier,
    framework,
    attempt,
    metrics,
    provenance: {
      frozenVersions: task.frozenVersions || makeFrozenVersions(),
      rtkCommit: getRtkCommit(path.join(__dirname, '..')),
      corpusVersion: getCorpusVersion(),
      benchmarkVersion: getBenchmarkVersion(),
      seed,
    },
    transcriptPath: transcriptPath || null,
  };
}

function nextAttemptNumber(runsDir, taskId, arm, modelId, framework) {
  const prefix = `${sanitizeName(taskId)}.${arm}.${sanitizeName(modelId)}.${sanitizeName(framework)}.`;
  let max = 0;
  if (fs.existsSync(runsDir)) {
    for (const f of fs.readdirSync(runsDir)) {
      const m = f.startsWith(prefix) && f.endsWith('.json') ? Number(f.slice(prefix.length, -'.json'.length)) : NaN;
      if (Number.isFinite(m)) max = Math.max(max, m);
    }
  }
  return max + 1;
}

// ---------------------------------------------------------------------------
// Live execution — never invoked in --plan/--dry-run mode
// ---------------------------------------------------------------------------

function seedWorkspace(task, workspace) {
  let seeded = false;
  if (task.taskDir && fs.existsSync(task.taskDir)) {
    for (const f of fs.readdirSync(task.taskDir)) {
      const src = path.join(task.taskDir, f);
      if (fs.statSync(src).isFile()) { fs.copyFileSync(src, path.join(workspace, f)); seeded = true; }
    }
  }
  if (task.prompt) { fs.writeFileSync(path.join(workspace, 'task.txt'), task.prompt); seeded = true; }
  return seeded;
}

function runTestsCommand(cmd, workspace) {
  const res = cp.spawnSync(cmd, { encoding: 'utf8', cwd: workspace, timeout: DEFAULT_TIMEOUT_MS, windowsHide: true, shell: true });
  return { ok: !res.error && res.status === 0, output: `${res.stdout || ''}${res.stderr || ''}` };
}

function classifyFailureMode(exitCode, timedOut) {
  if (timedOut) return 'timeout';
  if (exitCode < 0) return 'crash';
  return 'no-fix';
}

function runOneAttempt({ task, arm, model, framework, outDir, seed, customTemplate, timeoutMs }) {
  const attemptsDir = path.join(outDir, 'attempts');
  fs.mkdirSync(attemptsDir, { recursive: true });
  const workspace = fs.mkdtempSync(path.join(attemptsDir, `${sanitizeName(task.id)}-${arm}-`));
  const outSub = path.join(workspace, 'out');
  fs.mkdirSync(outSub, { recursive: true });
  seedWorkspace(task, workspace);
  const command = lib.resolveCommand(framework, { model: model.id, task: task.prompt || task.id, outdir: outSub }, customTemplate);
  const started = Date.now();
  const res = cp.spawnSync(command, {
    encoding: 'utf8', cwd: workspace, timeout: timeoutMs || DEFAULT_TIMEOUT_MS,
    windowsHide: true, shell: true, maxBuffer: 64 * 1024 * 1024,
    env: { ...process.env, RTK_ARM: arm, RTK_MODEL: model.id, NO_COLOR: '1', CI: '1' },
  });
  const wallClockMs = Date.now() - started;
  const timedOut = !!res.error && res.error.code === 'ETIMEDOUT';
  const transcriptText = `${res.stdout || ''}\n${res.stderr || ''}`;
  const lines = transcriptText.split('\n');
  const testResult = runTestsCommand(typeof task.tests === 'string' ? task.tests : task.tests.pass, workspace);
  const success = !timedOut && res.status === 0 && testResult.ok;
  const tokensOut = countTokens(transcriptText);
  const tokensIn = countTokens(task.prompt || '');
  const cost = lib.computeCost(tokensIn, tokensOut, model);
  const metrics = {
    success,
    testPass: testResult.ok,
    exitCode: timedOut ? -1 : res.status,
    retries: lib.estimateRetries(lines),
    toolCalls: lib.countToolCalls(lines),
    wallClockMs,
    inputTokens: tokensIn,
    outputTokens: tokensOut,
    contextTokens: model.contextWindow,
    costUsd: cost.usd,
    costEstimated: cost.estimated,
    failureMode: success ? null : classifyFailureMode(timedOut ? -1 : res.status, timedOut),
  };
  const transcriptPath = path.join(outSub, 'transcript.txt');
  fs.writeFileSync(transcriptPath, transcriptText);
  return buildRunRecord({ task, arm, model, framework, attempt: null, metrics, transcriptPath, seed });
}

async function executeAll(plan, opts) {
  const runsDir = path.join(opts.outDir, 'runs');
  fs.mkdirSync(runsDir, { recursive: true });
  const executable = plan.rows.filter((r) => r.available);
  const skipped = plan.rows.filter((r) => !r.available);
  const taskById = new Map(opts.tasks.map((t) => [t.id, t]));
  const modelById = new Map(opts.models.map((m) => [m.id, m]));
  const queue = executable.slice();
  const results = [];
  async function worker() {
    while (queue.length) {
      const row = queue.shift();
      const attempt = nextAttemptNumber(runsDir, row.taskId, row.arm, row.model, row.framework);
      const record = runOneAttempt({
        task: taskById.get(row.taskId), arm: row.arm, model: modelById.get(row.model),
        framework: row.framework, outDir: opts.outDir, seed: opts.seed,
        customTemplate: opts.frameworkCmd, timeoutMs: opts.timeoutMs,
      });
      record.attempt = attempt;
      const file = path.join(runsDir, `${sanitizeName(row.taskId)}.${row.arm}.${sanitizeName(row.model)}.${sanitizeName(row.framework)}.${attempt}.json`);
      fs.writeFileSync(file, JSON.stringify(record, null, 2));
      if (opts.blindJudge && record.transcriptPath && fs.existsSync(record.transcriptPath)) {
        const judgeDir = path.join(opts.outDir, 'judge');
        fs.mkdirSync(judgeDir, { recursive: true });
        const scrubbed = lib.scrubForBlindJudging(fs.readFileSync(record.transcriptPath, 'utf8'), { arm: row.arm, model: row.model, framework: row.framework });
        fs.writeFileSync(path.join(judgeDir, path.basename(file).replace('.json', '.scrubbed.txt')), scrubbed);
      }
      results.push(record);
      console.log(`[rtk external-eval] ran ${row.taskId} ${row.arm}/${row.model}/${row.framework} -> ${path.basename(file)} (success=${record.metrics.success})`);
    }
  }
  const workers = Array.from({ length: Math.max(1, opts.concurrency || 1) }, () => worker());
  await Promise.all(workers);
  return { results, skippedCount: skipped.length };
}


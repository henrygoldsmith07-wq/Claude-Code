function honestyBanner(tasks) {
  const independent = tasks.filter(lib.isIndependentTask);
  const internal = tasks.length - independent.length;
  if (independent.length === 0) {
    return [
      '> ## HONESTY BANNER',
      `> **NOT external evidence.** Tasks by source: ${internal} internal/synthetic, ${independent.length} independent.`,
      '> The word "external" is refused for this run: no task has source \'independent\'.',
      '> Synthetic/internal samples prove plumbing, never external validity.',
    ].join('\n');
  }
  return [
    '> ## HONESTY BANNER',
    `> Task sources: ${independent.length} independent, ${internal} internal/synthetic.`,
    `> Only the ${independent.length} independent task(s) support external claims; internal rows are shown for plumbing diagnostics only.`,
  ].join('\n');
}

function renderSummaryMd(compare, meta) {
  const pct = (x) => `${(x * 100).toFixed(1)}%`;
  const ci = (w) => `[${pct(w.lower)}, ${pct(w.upper)}]`;
  const lines = [];
  lines.push('# RTK external-benchmark summary');
  lines.push('');
  lines.push(meta.banner);
  lines.push('');
  lines.push(`Generated: ${meta.generatedAt}`);
  lines.push(`Seed: ${meta.seed} | Frameworks: ${meta.frameworks.join(', ') || 'n/a'} | Models: ${meta.models.join(', ') || 'n/a'}`);
  lines.push('');
  lines.push('| Arm | n | Success rate | Wilson 95% CI | Mean tool calls | Mean wall ms | Mean in tok | Total $ |');
  lines.push('| --- | ---: | ---: | --- | ---: | ---: | ---: | ---: |');
  for (const armName of ['raw', 'rtk']) {
    const a = compare[armName];
    lines.push(`| ${a.n ? armName : `${armName} (no runs)`} | ${a.n} | ${pct(a.successRate)} | ${a.n ? ci(a.wilson) : '—'} | ${a.meanToolCalls.toFixed(2)} | ${Math.round(a.meanWallClockMs)} | ${Math.round(a.meanInputTokens)} | ${a.totalCostUsd.toFixed(4)} |`);
  }
  lines.push('');
  lines.push(`Difference (rtk − raw): ${(compare.difference.point * 100).toFixed(1)} points, paired TOST 90% CI [${(compare.difference.lower * 100).toFixed(1)}, ${(compare.difference.upper * 100).toFixed(1)}] vs ±${(compare.difference.margin * 100).toFixed(0)} margin.`);
  lines.push(`Verdict: **${compare.verdict}** — ${compare.tost.note}`);
  lines.push(`McNemar: ${compare.mcnemar.note}`);
  lines.push('');
  lines.push('> Equivalence wording follows src/equivalence.js: absence of a significant difference is NOT equivalence.');
  return `${lines.join('\n')}\n`;
}


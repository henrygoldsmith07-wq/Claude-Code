'use strict';

/**
 * External-benchmark runner — raw-vs-RTK on independently-sourced coding-agent
 * tasks across model tiers and agent frameworks.
 *
 * Infrastructure only until pointed at real task sources: --plan/--dry-run
 * prints the full planned matrix (tasks x arms x models x frameworks) with
 * availability and executes nothing; --gen-sample writes clearly-marked
 * synthetic placeholder tasks that can never support an external claim.
 *
 * Usage:
 *   node benchmark/external-eval.js --help
 *   node benchmark/external-eval.js --gen-sample
 *   node benchmark/external-eval.js --tasks benchmark/tasks.sample.jsonl --arm both \
 *     --tier medium --framework generic --framework-cmd 'node script.js {model} {task} {outdir}' --plan
 */

const fs = require('fs');
const path = require('path');
const os = require('os');
const cp = require('child_process');
const lib = require('./external-eval-lib');
const { MODEL_REGISTRY } = require('../src/providers');
const { getRtkCommit, getBenchmarkVersion, getCorpusVersion } = require('../src/provenance');

let countTokens;
try { ({ countTokens } = require('../src/tokens')); }
catch { countTokens = (s) => Math.round(String(s).length / 4); }

const DEFAULT_TIMEOUT_MS = 15_000;

// On Windows most CLIs ship as .cmd/.exe shims spawnSync cannot resolve
// without a shell — probe candidates like benchmark/capture.js does.
function binCandidates(bin) {
  return process.platform === 'win32' ? [`${bin}.cmd`, `${bin}.exe`, bin] : [bin];
}

/** Availability probe: `<bin> --version` must exit 0. Never throws. */
function probeAvailability(frameworkId) {
  const entry = lib.FRAMEWORKS[frameworkId];
  if (!entry || !entry.bin) return { framework: frameworkId, available: false, reason: entry ? 'generic adapter needs --framework-cmd' : 'unknown framework' };
  for (const bin of binCandidates(entry.bin)) {
    const res = cp.spawnSync(bin, ['--version'], {
      encoding: 'utf8', timeout: DEFAULT_TIMEOUT_MS, windowsHide: true,
      shell: process.platform === 'win32', stdio: ['ignore', 'pipe', 'ignore'],
    });
    if (!res.error && res.status === 0) return { framework: frameworkId, available: true, bin };
  }
  return { framework: frameworkId, available: false, reason: `${entry.bin} --version not found` };
}


'use strict';

const { requiredPairs } = require('./equivalence');

// ---------------------------------------------------------------------------
// The real corpus, and why the synthetic one cannot stand in for it.
//
// RTK's evidence today comes from `benchmark/fixtures.js` — generated output
// shaped like vitest, tsc and Next. Those fixtures are honest about being
// generated, and they are genuinely useful: they make the reduction numbers
// reproducible and they catch regressions.
//
// What they cannot do is support a claim about real tool output, for a reason
// specific to this product. The fixtures were written by the same person who
// wrote the parsers, so the parsers see exactly the shapes they were built
// for. Real output has the things nobody thinks to generate: interleaved
// stderr, a progress spinner's carriage returns, a stack from a transitive
// dependency, a test name containing a line that looks like an error, output
// truncated mid-token by a CI runner's buffer. A 99.9% reduction on a fixture
// is a measurement of the fixture.
//
// So this module defines the two real corpora the claim needs, with the
// provenance that makes each entry checkable, and refuses to let a synthetic
// corpus be reported as either. Both ship empty.
//
// Pure. No I/O — collection belongs to `benchmark/corpus-builder.js`.
// ---------------------------------------------------------------------------

const PROVENANCE = {
  synthetic: 'Generated by benchmark/fixtures.js. Regression guard only; never a measurement of real tool output.',
  captured: 'Real stdout/stderr captured from a real command run, stored with the command, exit code and tool version.',
};

/**
 * One real agent task.
 *
 * `command`, `exitCode` and `capturedAt` are what make it checkable, and
 * `fixNeedles` is what makes it scorable — the specific strings a correct
 * answer must contain. Needles are recorded by whoever captured the case,
 * from the real failure they were actually debugging, which is the part no
 * generator can produce.
 */
function emptyAgentCorpus() {
  return { provenance: 'captured', tasks: [], collectedFrom: [] };
}

/** One real CI log, kept whole so parsers meet the mess they will meet in production. */
function emptyCiCorpus() {
  return { provenance: 'captured', logs: [], collectedFrom: [] };
}

/**
 * Targets, recorded so the gap between the claim and the evidence stays visible.
 *
 * `agentTasks` is 1000 because the brief asks for it and because the
 * equivalence maths agrees: ~248 pairs are the minimum to show a ±5-point
 * margin at 80% power, and 1000 leaves room to slice by tool and by model
 * without every subgroup being underpowered.
 */
const TARGETS = {
  agentTasks: 1000,
  ciLogs: 200,
  minToolsCovered: 8,
  minRepos: 5,
};

function corpusStats(corpus) {
  const items = corpus.tasks ?? corpus.logs ?? [];
  const tools = new Set(items.map((t) => t.tool).filter(Boolean));
  const repos = new Set(items.map((t) => t.repo).filter(Boolean));
  return {
    provenance: corpus.provenance,
    count: items.length,
    tools: tools.size,
    repos: repos.size,
    withNeedles: items.filter((t) => Array.isArray(t.fixNeedles) && t.fixNeedles.length > 0).length,
    summary:
      items.length === 0
        ? `Empty ${corpus.provenance} corpus: 0 entries. Nothing here can be reported as a measurement.`
        : `${items.length} ${corpus.provenance} entries across ${tools.size} tool(s) and ${repos.size} repo(s).`,
  };
}

/**
 * Whether a corpus may back the headline claim.
 *
 * Coverage is gated as well as size, because 1000 cases from one repo running
 * one test runner would satisfy the sample-size maths and still say nothing
 * about the tool nobody tested. The failure this prevents is a benchmark that
 * is large, green, and narrow.
 */
function corpusEligibility(corpus, targets = TARGETS) {
  const stats = corpusStats(corpus);
  const reasons = [];
  const isAgent = Array.isArray(corpus.tasks);
  const wanted = isAgent ? targets.agentTasks : targets.ciLogs;

  if (corpus.provenance !== 'captured') {
    reasons.push('Corpus is synthetic — usable as a regression guard, never as evidence about real output.');
  }
  if (stats.count < wanted) {
    reasons.push(`${stats.count} entries; the claim needs at least ${wanted}.`);
  }
  if (stats.tools < targets.minToolsCovered) {
    reasons.push(`${stats.tools} tool(s) covered; at least ${targets.minToolsCovered} needed, or the result only describes the tools that were tested.`);
  }
  if (stats.repos < targets.minRepos) {
    reasons.push(`${stats.repos} repo(s); at least ${targets.minRepos} needed so the result is not one codebase's habits.`);
  }
  if (isAgent && stats.withNeedles < stats.count) {
    reasons.push(`${stats.count - stats.withNeedles} task(s) have no fixNeedles and cannot be scored.`);
  }

  return { eligible: reasons.length === 0, reasons, stats };
}

/** One line for the benchmark report, including when the answer is "not yet". */
function corpusReport(agentCorpus, ciCorpus) {
  const agent = corpusEligibility(agentCorpus);
  const ci = corpusEligibility(ciCorpus);
  const need = requiredPairs();
  const lines = [
    `Agent-task corpus: ${agent.stats.summary}`,
    `  Reportable: ${agent.eligible ? 'yes' : 'no'}`,
    ...agent.reasons.map((r) => `    - ${r}`),
    `CI corpus: ${ci.stats.summary}`,
    `  Reportable: ${ci.eligible ? 'yes' : 'no'}`,
    ...ci.reasons.map((r) => `    - ${r}`),
    `Statistics: ${need.note}`,
  ];
  return { agent, ci, text: lines.join('\n') };
}

module.exports = {
  PROVENANCE,
  TARGETS,
  emptyAgentCorpus,
  emptyCiCorpus,
  corpusStats,
  corpusEligibility,
  corpusReport,
};
